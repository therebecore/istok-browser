package io.github.therebecore.istok

import android.content.Context
import android.util.AttributeSet
import android.view.MotionEvent
import android.view.inputmethod.EditorInfo
import android.view.inputmethod.InputConnection
import android.webkit.WebView

/**
 * WebView, у которого ввод забирает наша экранная клавиатура, а не системная.
 *
 * На телевизоре системный IME - окно во весь экран поверх нашего: `dumpsys window`
 * на стенде показывает `InputMethod` с рамкой [0,0][1920,1080]. Пока оно открыто,
 * до нашей клавиатуры (ADR-020..022) не доходит ни одно нажатие - все достаются ему.
 * Поднимает его сам движок, как только фокус попадает в поле страницы.
 *
 * Перехват стоит там, где движок отдаёт соединение ввода: это тот самый момент,
 * когда система собирается показать клавиатуру. Соединение мы забираем себе -
 * через него в поле уходят символы, которых нет в раскладке платформы (кириллица),
 * а окно системного IME убираем.
 */
internal class BrowserWebView @JvmOverloads constructor(
    context: Context,
    attrs: AttributeSet? = null,
) : WebView(context, attrs) {

    /** Соединение с полем страницы, в которое сейчас идёт ввод. `null` - поля нет. */
    var connection: InputConnection? = null
        private set

    /**
     * Движок просит клавиатуру: фокус попал в поле страницы. Сигнал точнее хит-теста
     * из ADR-022 - он приходит и для `contenteditable`, и для редакторов на div,
     * которые `getHitTestResult` показывает обычным блоком (ADR-023).
     */
    var onInputStarted: (() -> Unit)? = null

    /**
     * То же событие, но **синхронно** и до того, как соединение уйдёт системе.
     *
     * Разница решающая. [onInputStarted] приходит следующим проходом очереди, а система
     * к этому моменту уже решает показать своё окно: запрет флагом окна опаздывает,
     * и на прошивке Яндекс ТВ клавиатура телевизора вставала поверх нашей (`B-43`,
     * вторая итерация). Здесь же мы стоим ровно в том вызове, которым система спрашивает
     * соединение, - флаг, поставленный отсюда, действует уже на этот показ.
     *
     * Внутри можно менять только состояние окна. Показывать View отсюда нельзя -
     * для этого есть [onInputStarted].
     */
    var onInputStarting: (() -> Unit)? = null

    /**
     * Забыть соединение: поле, к которому оно вело, больше не то, куда целится
     * пользователь. Иначе набранное или вставленное уходило бы в документ, которого
     * на экране уже нет.
     */
    fun releaseConnection() {
        connection = null
    }

    /**
     * Пользователь коснулся страницы. Единственный сигнал, по которому видно, что место
     * ввода выбрал он сам, а не сайт: клики по нашей клавиатуре и панели сюда не доходят,
     * их забирают View, лежащие выше.
     */
    var onTouched: (() -> Unit)? = null

    /**
     * Пользователь закрыл клавиатуру, а поле страницы фокус не отдало: соединение
     * в этом состоянии движку не выдаётся.
     *
     * Это защита от системной клавиатуры телевизора, и слабее неё ничего не сработало.
     * Проверено на стенде, каждое отдельно: запрет показа флагом окна не действует,
     * если система уже привязана к окну; `hideSoftInputFromWindow` приходит раньше
     * самого показа, и повтор следующим проходом очереди не помогает; объявление поля
     * нетекстовым (`InputType.TYPE_NULL`) заставляет телевизор поднять полноэкранную
     * таблицу символов - хуже прежнего. Отказ в соединении не оставляет системе
     * ничего, что можно обслуживать.
     */
    var inputSuppressed = false

    /**
     * Касание пришло от нашей же прокрутки протяжкой (ADR-042), а не от человека.
     * Такое касание не выбирает место ввода, поэтому [onTouched] по нему не срабатывает.
     * Ставится на время отправки события в [CursorController].
     */
    var synthetic = false

    // Наблюдение, а не обработка: событие мы не потребляем и клик не имитируем, поэтому
    // берётся `dispatchTouchEvent`, а не `onTouchEvent` - у второго переопределение
    // без `performClick` ломает доступность и справедливо ругается линтом.
    override fun dispatchTouchEvent(event: MotionEvent): Boolean {
        if (event.actionMasked == MotionEvent.ACTION_DOWN && !synthetic) onTouched?.invoke()
        return super.dispatchTouchEvent(event)
    }

    override fun onCreateInputConnection(outAttrs: EditorInfo): InputConnection? {
        if (inputSuppressed) return null
        val created = super.onCreateInputConnection(outAttrs)
        connection = created
        if (created != null) {
            // Сначала синхронно - закрыть окно от системного IME, пока он не показан.
            onInputStarting?.invoke()
            // И только потом отложенно: сейчас мы внутри вызова самой системы,
            // и показывать свои View отсюда нельзя.
            post { onInputStarted?.invoke() }
        }
        return created
    }
}
